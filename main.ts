// PORT VESPER hand-in entry. The deliverable is the self-contained game/ folder: plain static
// files that a browser opens offline, with no build step, no packages and no network fetches.
// This script copies that folder plus the captured shots to the output directory and asks the
// vendored make.fun library to describe the result. vendor/ is used as-is and never changed.

import { cpSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildDossier } from './vendor/makefun-game.ts';

const root = fileURLToPath(new URL('.', import.meta.url));
const output = process.env.MAKEFUN_OUTPUT_DIR ?? '/output';

mkdirSync(output, { recursive: true });
cpSync(join(root, 'game'), join(output, 'game'), { recursive: true });

mkdirSync(join(output, 'screenshots'), { recursive: true });
if (existsSync(join(root, 'screenshots'))) {
  cpSync(join(root, 'screenshots'), join(output, 'screenshots'), { recursive: true });
}

// The scorer's own limits: only text_max_bytes changes the dossier bytes. The rest refuse a
// submission the scorer would refuse, so passing them keeps local output identical to graded.
writeFileSync(
  join(output, 'dossier.json'),
  buildDossier(output, {
    text_max_bytes: 163840,
    screenshots: { max: 4, max_bytes: 262144 },
    game_max_files: 993,
    game_max_bytes: 50331648,
    game_path_max_bytes: 1000,
  }),
);
